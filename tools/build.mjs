#!/usr/bin/env node
// Builds the hosted site from the single source file web/snug.html.
//
//   node tools/build.mjs
//
// Outputs (commit them; GitHub Pages serves them as-is):
//   docs/index.html, docs/manifest.webmanifest, docs/sw.js   used when Pages serves the /docs folder
//   index.html, manifest.webmanifest, sw.js                  the same site when Pages serves the repo root
//                                                            (fonts and icons are referenced under docs/)
// The source file keeps its Google Fonts link so it also works as a standalone preview; the hosted
// build swaps that for the bundled font files in docs/fonts so the game works offline.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const src = readFileSync(join(root, "web/snug.html"), "utf8");

const build = (src.match(/const BUILD="(\w+)"/) || [])[1];
if (!build) throw new Error("BUILD constant not found in web/snug.html");

// Body = source minus its own <title>, preview-only meta and Google Fonts links.
const body = src
  .replace(/^<title>.*<\/title>\n/m, "")
  .replace(/^<meta name="claude:[^>]*>\n/m, "")
  .replace(/^<link [^>]*fonts\.(googleapis|gstatic)\.com[^>]*>\n/gm, "");
if (/fonts\.googleapis/.test(body)) throw new Error("Google Fonts link was not removed");

const FONTS = [
  ["Lilita One", 400, "lilita-one-latin-400-normal.woff2"],
  ["Nunito", 800, "nunito-latin-800-normal.woff2"],
  ["Nunito", 900, "nunito-latin-900-normal.woff2"],
];

const page = (assets) => `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover, user-scalable=no">
<title>Snug</title>
<meta name="description" content="Snug: hold to grow, let go to shrink, fit the gap. A one-thumb game by Snugworks.">
<meta property="og:title" content="Snug">
<meta property="og:description" content="Hold to grow. Let go to shrink. Fit the gap!">
<meta name="apple-mobile-web-app-capable" content="yes">
<meta name="mobile-web-app-capable" content="yes">
<meta name="apple-mobile-web-app-title" content="Snug">
<meta name="apple-mobile-web-app-status-bar-style" content="black-translucent">
<meta name="theme-color" content="#56c3f0">
<meta http-equiv="Cache-Control" content="no-cache, must-revalidate">
<link rel="manifest" href="manifest.webmanifest">
<link rel="icon" type="image/png" sizes="192x192" href="${assets}icons/icon-192.png">
<link rel="apple-touch-icon" href="${assets}icons/apple-touch-icon.png">
<style>
:root{padding-top:env(safe-area-inset-top,0px);padding-bottom:env(safe-area-inset-bottom,0px)}body{margin:0}img{max-width:100%}
${FONTS.map(([family, weight, file]) => `@font-face{font-family:"${family}";font-weight:${weight};font-display:swap;src:url("${assets}fonts/${file}") format("woff2")}`).join("\n")}
</style>
</head>
<body>
${body.trimEnd()}
</body>
</html>
`;

const manifest = (assets) => JSON.stringify({
  name: "Snug",
  short_name: "Snug",
  description: "Hold to grow. Let go to shrink. Fit the gap!",
  start_url: "./",
  scope: "./",
  display: "standalone",
  orientation: "portrait",
  background_color: "#56c3f0",
  theme_color: "#56c3f0",
  icons: [
    { src: `${assets}icons/icon-192.png`, sizes: "192x192", type: "image/png" },
    { src: `${assets}icons/icon-512.png`, sizes: "512x512", type: "image/png" },
    { src: `${assets}icons/maskable-512.png`, sizes: "512x512", type: "image/png", purpose: "maskable" },
  ],
}, null, 2) + "\n";

// Network first (players always get the newest build when online), cached copy when offline.
const sw = (assets) => `// Generated by tools/build.mjs. Snug build ${build}.
const CACHE = "snug-${build}";
const ASSETS = ${JSON.stringify(["./", ...FONTS.map((f) => `${assets}fonts/${f[2]}`), `${assets}icons/icon-192.png`])};
const keyOf = (url) => url.split("?")[0];

self.addEventListener("install", (event) => {
  self.skipWaiting();
  event.waitUntil(caches.open(CACHE).then((cache) => Promise.allSettled(ASSETS.map((a) => cache.add(a)))));
});
self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((k) => k.startsWith("snug-") && k !== CACHE).map((k) => caches.delete(k))))
      .then(() => self.clients.claim())
  );
});
self.addEventListener("fetch", (event) => {
  const request = event.request;
  if (request.method !== "GET" || new URL(request.url).origin !== location.origin) return;
  event.respondWith(
    fetch(request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(keyOf(request.url), copy));
        }
        return response;
      })
      .catch(() => caches.match(keyOf(request.url)).then((hit) => hit || caches.match("./")))
  );
});
`;

for (const [dir, assets] of [["docs", ""], ["", "docs/"]]) {
  writeFileSync(join(root, dir, "index.html"), page(assets));
  writeFileSync(join(root, dir, "manifest.webmanifest"), manifest(assets));
  writeFileSync(join(root, dir, "sw.js"), sw(assets));
}
console.log(`Built Snug build ${build}: docs/ and repo root`);
